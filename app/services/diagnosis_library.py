def search(group="", query=""):
    terms = re.split(r"[\s,;]+", query.strip().casefold().replace("ё", "е"))
    return [
        dict(
            code=code,
            name=name,
            group=key,
            group_label=GROUPS[key],
            search_text=code + " " + name + " " + GROUPS[key] + " " + ALIASES[key],
        )
        for code, name, key in ENTRIES
        if (not group or group == key)
        and (
            all(
                term
                in (code + " " + name + " " + GROUPS[key] + " " + ALIASES[key])
                .casefold()
                .replace("ё", "е")
                for term in terms
            )
        )
    ]
