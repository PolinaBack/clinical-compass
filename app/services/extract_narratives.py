def hcl_context(key, answer, choices):
    topics = {
        "today": "Самочувствие сегодня по сравнению с обычным",
        "usual": "Обычный уровень активности, энергии и настроения относительно других людей",
        "impact_family": "Влияние периодов подъёма на семью",
        "impact_social": "Влияние периодов подъёма на общение",
        "impact_work": "Влияние периодов подъёма на работу",
        "impact_leisure": "Влияние периодов подъёма на досуг",
        "reaction": "Реакция близких на периоды подъёма",
        "longest": "Самый длительный период подъёма",
        "average": "Средняя длительность периода подъёма",
        "year": "Наличие периодов подъёма за последние 12 месяцев",
        "days": "Число дней подъёма за последние 12 месяцев",
        "temperament": "Свойственные по натуре периоды подъёмов и спадов",
        "swings": "Внезапные перепады настроения",
    }
    topic = topics.get(key, "Контекст периодов подъёма")
    value = answer.get("value")
    if answer.get("state") != "answered" or value is None:
        return sentence(
            f"Сведения по теме «{topic}» не уточнены; отсутствие ответа не означает отрицательный результат"
        )
    if choices and (not isinstance(value, int) or not 0 <= value < len(choices)):
        return sentence(f"Сведения по теме «{topic}» требуют проверки исходного ответа")
    label = choices[value] if choices else str(value)
    return sentence(f"Пациент описывает {lower(topic)} следующим образом: «{label}»")
