def sentence(value):
    value = str(value).strip()
    return value + ("" if not value or value[-1] in ".!?…" else ".")


def lower(value):
    return value[:1].lower() + value[1:] if value and not value[:2].isupper() else value


def field_text(scope, field, answer, *, context=""):
    key, state = field["key"], answer.get("status")
    if state in (None, "unanswered"):
        return ""
    topic, template = (
        (ENTITIES if scope in ENTITIES and context == "entity" else FIELDS)
        .get(scope, {})
        .get(
            key,
            COMMON.get(
                key,
                ("дополнительные сведения", "Пациент дополнительно сообщает: «{v}»"),
            ),
        )
    )
    if state != "answered":
        descriptions = {
            "unknown": "пациент не знает",
            "not_remembered": "пациент не помнит",
            "skipped": "пациент пока пропустил этот пункт",
            "discuss": "пациент предпочитает обсудить лично",
            "declined": "пациент предпочёл не сообщать",
        }
        return sentence(
            f"Сведения по теме «{topic}» не уточнены: {descriptions.get(state, 'ответ не завершён')}"
        )
    raw = answer.get("value")
    if key == "discuss":
        return (
            "Пациент хочет обсудить этот раздел лично."
            if raw == "Да"
            else "Пациент не отметил необходимости личного обсуждения этого раздела."
        )
    if (scope, key) in BOOL:
        topic = BOOL[scope, key]
        if raw == "Да":
            return sentence("Пациент отмечает " + topic)
        if raw == "Нет":
            return sentence("Пациент отрицает " + topic)
        if raw in ("Не уверен(а)", "Не знаю", "Затрудняюсь ответить", "Не помню"):
            return sentence(
                f"Сведения про {topic} требуют уточнения; пациент не уверен в ответе"
            )
    if (
        scope == "health"
        and key == "known_conditions"
        and raw == "Нет известных заболеваний"
    ):
        return "Пациент не сообщает об известных ему заболеваниях; полнота анамнеза требует проверки врачом."
    if scope == "reproductive" and key == "pregnancy" and raw == "Нет":
        return "Пациент отрицает беременность, лактацию и значимую для лечения вероятность беременности."
    if not isinstance(raw, (list, dict)) and raw in CHOICES.get((scope, key), {}):
        return CHOICES[scope, key][raw]
    if scope == "complaints" and key in ("other", "comment"):
        complaints = {
            "беспокойство": "беспокойство",
            "тревога": "тревогу",
            "бессонница": "бессонницу",
            "усталость": "усталость",
            "боль": "боль",
            "раздражительность": "раздражительность",
            "страх": "страх",
            "грусть": "грусть",
            "стресс": "стресс",
        }
        if str(raw).strip().casefold().rstrip(".") in complaints:
            return sentence(
                "Пациент жалуется на "
                + complaints[str(raw).strip().casefold().rstrip(".")]
            )
        template = "Пациент описывает жалобы: «{v}»"
    value = display_field(field, answer)
    if scope == "complaints" and key.startswith("complaint_") and isinstance(raw, list):
        value = ", ".join(COMPLAINTS.get(v, lower(v)) for v in raw)
    if field.get("kind") == "date":
        try:
            value = date.fromisoformat(str(raw)).strftime("%d.%m.%Y")
        except ValueError:
            pass
    if isinstance(raw, list) and not raw:
        return sentence(
            f"По теме «{topic}» пациент не выбрал ни одного варианта; это не подтверждает отсутствие сведений"
        )
    if (scope, key) in {
        ("measurements", "weight_change"),
        ("daily", "appetite"),
        ("reproductive", "regular"),
    }:
        value = lower(value)
    return sentence(template.format(v=value))


