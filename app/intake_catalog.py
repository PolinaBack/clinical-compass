def f(key, label, kind="text", options=None, **kw):
    return dict(key=key, label=label, kind=kind, options=options or [], **kw)


def q(key, label, options=YES, **kw):
    return f(key, label, "choice", options, **kw)


def scale(key, label, **kw):
    return f(key, label, "scale", minimum=0, maximum=10, **kw)


def when(key, *values):
    return dict(key=key, values=list(values))


def category(
    key,
    title,
    description,
    group,
    bg,
    accent,
    icon,
    fields,
    page,
    kinds=(),
    sensitive=False,
):
    fields += [
        f("comment", "Комментарий · по желанию", "longtext"),
        q("discuss", "Хочу обсудить раздел лично", ["Да", "Нет"]),
    ]
    return dict(
        key=key,
        title=title,
        description=description,
        group=group,
        bg=bg,
        accent=accent,
        icon=icon,
        fields=fields,
        source_pages=page,
        kinds=list(kinds),
        sensitive=sensitive,
    )


