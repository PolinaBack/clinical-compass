def symptom_category(scale, total):
    """Supplement pp.18: symptom descriptions, never diagnosis or urgency."""
    if total is None or scale not in ["phq9", "gad7"]:
        return None
    if total < 5:
        return "Минимальные симптомы"
    if total < 10:
        return "Лёгкие симптомы"
    if total < 15:
        return "Умеренные симптомы"
    if scale == "phq9" and total < 20:
        return "Умеренно тяжёлые симптомы"
    return "Тяжёлые симптомы"
