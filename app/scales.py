def score(scale, answers):
    """Nulls never become zero; each PHQ-4 subscale has its own completeness."""
    if scale == "safety6":
        return safety_result(answers)
    definition = SCALES[scale]
    values = [
        (
            answers.get(str(i), {}).get("value")
            if answers.get(str(i), {}).get("state") == "answered"
            else None
        )
        for i in range(1, len(definition["items"]) + 1)
    ]
    maximum = 1 if scale == "hcl33" else 3
    if any(
        v is not None
        and (not isinstance(v, int) or isinstance(v, bool) or not 0 <= v <= maximum)
        for v in values
    ):
        raise ValueError("Недопустимый ответ")
    result = {
        "answered": sum(v is not None for v in values),
        "count": len(values),
        "total": sum(values) if all(v is not None for v in values) else None,
    }
    if scale == "phq4":
        result["gad2"] = (
            sum(values[:2]) if all(v is not None for v in values[:2]) else None
        )
        result["phq2"] = (
            sum(values[2:]) if all(v is not None for v in values[2:]) else None
        )
    if scale == "phq9":
        result["needs_safety_clarification"] = values[8] is not None and values[8] > 0
    return result


def combined(phq9, gad7):
    if not phq9 or not gad7:
        return None, "Нужны обе формы одной сессии"
    for key in ["session_id", "period_start", "period_end", "version"]:
        if phq9[key] != gad7[key]:
            return None, "Периоды, сессии или версии не совпадают"
    if phq9["total"] is None or gad7["total"] is None:
        return None, "Одна из форм не завершена"
    return (
        phq9["total"] + gad7["total"],
        "Исследовательский показатель; не диагноз и не оценка безопасности",
    )


